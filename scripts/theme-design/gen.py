#!/usr/bin/env python3
"""Generates the built-in themes' primitive palettes, their color blocks, and their design docs from themes.py.

Usage (from the repository root):

    python3 scripts/theme-design/audit.py   # must report 0 violations
    python3 scripts/theme-design/gen.py

Writes:
- Sources/SwiftForgeUI/Tokens/Primitives/SwiftForgePalette+<Theme>.swift   (complete files)
- .build/theme-design/colors-<id>.swift.txt  (the `accent`/`colors` block to paste into SwiftForgeTheme+<Theme>.swift)
- docs/design/themes/<id>.md                 (role table and contrast ratios)

SwiftForgeContrastAudit re-verifies the Swift values in every test run; this tool only designs them.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from colorlib import contrast, hx, ramp  # noqa: E402
from themes import THEMES, palette  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TONES = ['accent', 'neutral', 'info', 'success', 'warning', 'danger']
ENUM = {'midnight': 'Midnight', 'aurora': 'Aurora', 'paper': 'Paper', 'neoBrutal': 'NeoBrutal', 'mono': 'Mono', 'ocean': 'Ocean',
        'sunset': 'Sunset'}
THEME_ID = {'neoBrutal': 'neo-brutal'}
APPEARANCES = ['light', 'dark', 'light HC', 'dark HC']


def ref(r):
    if r == 'white':
        return 'Palette.white'
    if r == 'black':
        return 'Palette.black'
    if '.' in r:
        h, s = r.split('.')
        return f'P.{h}.s{s}'
    return f'P.{r}'


def color(r4):
    light, dark, lhc, dhc = r4
    args = [f'light: {ref(light)}', f'dark: {ref(dark)}']
    if lhc != light:
        args.append(f'lightHighContrast: {ref(lhc)}')
    if dhc != dark:
        args.append(f'darkHighContrast: {ref(dhc)}')
    return f'SwiftForgeColor({", ".join(args)})'


def palette_file(key):
    t = THEMES[key]
    e = ENUM[key]
    lines = ['//', f'//  SwiftForgePalette+{e}.swift', '//  SwiftForgeUI', '//',
             f'//  Primitives of the {t["name"]} theme, generated by scripts/theme-design. Each ramp holds one',
             '//  hue at fixed perceptual (OKLab) lightness steps, so the same step contrasts alike across',
             '//  hues; named colors are hand-picked accents and surfaces.', '//', '',
             'extension Palette {', '', f'    enum {e} {{', '']
    for name, anchor in t['ramps'].items():
        lines.append(f'        enum {name} {{')
        for step, value in ramp(anchor).items():
            lines.append(f'            static let s{step}: UInt32 = 0x{value}')
        lines += ['        }', '']
    for name, value in t.get('extras', {}).items():
        lines.append(f'        static let {name}: UInt32 = 0x{value.lstrip("#")}')
    lines += ['    }', '}', '']
    with open(os.path.join(ROOT, 'Sources/SwiftForgeUI/Tokens/Primitives', f'SwiftForgePalette+{e}.swift'), 'w') as f:
        f.write('\n'.join(lines))


def tone(t, n):
    tn = t['tones'][n]
    args = [f'solid: {color(tn["solid"])}', f'onSolid: {color(tn["onSolid"])}', f'text: {color(tn["text"])}',
            f'subtle: {color(tn["subtle"])}']
    if tn.get('solidFill'):
        stops = ', '.join(color(s) for s in tn['solidFill'])
        args.append(f'solidFill: .linearGradient([{stops}], startPoint: .leading, endPoint: .trailing)')
    return 'SwiftForgeToneColors(' + ', '.join(args) + ')'


def colors_block(key):
    t = THEMES[key]
    c = t['colors']
    out = ['let accent = ' + tone(t, 'accent'), 'let colors = SwiftForgeColors(']
    for role in ['canvas', 'surface', 'surfaceRaised', 'fillMuted', 'textPrimary', 'textSecondary', 'borderSubtle',
                 'borderStrong']:
        out.append(f'    {role}: {color(c[role])},')
    out += ['    focusRing: accent.text,', '    pressedOverlay: SharedTokens.pressedOverlay,', '    accent: accent,']
    for n in TONES[1:]:
        out.append(f'    {n}: {tone(t, n)}' + (',' if n != 'danger' else ''))
    out.append(')')
    return '\n'.join(out) + '\n'


def doc(key):
    t = THEMES[key]
    p = palette(t)
    c = t['colors']

    def cell(r):
        return f'`{r}` `#{p[r]}`'

    def ratio(fg, bg, i):
        return f'{contrast(hx(p[fg[i]]), hx(p[bg[i]])):.2f}'

    lines = [f'# {t["name"]}', '',
             f'> `SwiftForgeTheme.{key}` · id `"{THEME_ID.get(key, key)}"` · Generated by `scripts/theme-design/gen.py` — do not edit by hand.',
             '', f'**Character:** {t["character"]}', '',
             'Tokens other than color (shape, shadow, typography, density, motion, and component tokens) and the reasons for',
             f'them are in the doc comment in `Sources/SwiftForgeUI/Themes/SwiftForgeTheme+{ENUM[key]}.swift`.', '',
             '## Palette', '',
             '| Ramp | Anchor | 50 | 300 | 500 | 700 | 950 |', '|---|---|---|---|---|---|---|']
    for name, anchor in t['ramps'].items():
        r = ramp(anchor)
        lines.append(f'| {name} | `{anchor}` | ' + ' | '.join(f'`#{r[s]}`' for s in (50, 300, 500, 700, 950)) + ' |')
    lines += ['', 'Named colors: ' + ', '.join(f'`{k}` `{v}`' for k, v in t.get('extras', {}).items()), '',
              '## Semantic roles', '', '| Role | ' + ' | '.join(APPEARANCES) + ' |', '|---|---|---|---|---|']
    for role in ['canvas', 'surface', 'surfaceRaised', 'fillMuted', 'textPrimary', 'textSecondary', 'borderSubtle',
                 'borderStrong']:
        lines.append(f'| `{role}` | ' + ' | '.join(cell(r) for r in c[role]) + ' |')
    for n in TONES:
        for part in ['solid', 'onSolid', 'text', 'subtle']:
            lines.append(f'| `{n}.{part}` | ' + ' | '.join(cell(r) for r in t['tones'][n][part]) + ' |')
        if t['tones'][n].get('solidFill'):
            stops = t['tones'][n]['solidFill']
            lines.append(f'| `{n}.solidFill` | ' + ' | '.join(
                ' → '.join(f'`#{p[s[i]]}`' for s in stops) for i in range(4)) + ' |')
    lines += ['', '## Contrast (WCAG 2.x)', '',
              '`SwiftForgeContrastAudit` and `scripts/theme-design/audit.py` check every role pair, gradient midpoints, and',
              'component tokens; the selection below shows the pairs read most often.', '',
              '| Pair | Required | ' + ' | '.join(APPEARANCES) + ' |', '|---|---|---|---|---|---|']
    pairs = [('textPrimary', c['textPrimary'], 'surface', c['surface'], '4.5'),
             ('textSecondary', c['textSecondary'], 'canvas', c['canvas'], '4.5'),
             ('textSecondary', c['textSecondary'], 'surface', c['surface'], '4.5'),
             ('accent.onSolid', t['tones']['accent']['onSolid'], 'accent.solid', t['tones']['accent']['solid'], '4.5'),
             ('accent.text', t['tones']['accent']['text'], 'surface', c['surface'], '4.5'),
             ('danger.text', t['tones']['danger']['text'], 'danger.subtle', t['tones']['danger']['subtle'], '4.5'),
             ('borderStrong', c['borderStrong'], 'surface', c['surface'], '3'),
             ('accent.text', t['tones']['accent']['text'], 'fillMuted', c['fillMuted'], '3')]
    for fg_name, fg, bg_name, bg, req in pairs:
        lines.append(f'| `{fg_name}` / `{bg_name}` | {req} | ' + ' | '.join(ratio(fg, bg, i) for i in range(4)) + ' |')
    lines.append('')
    os.makedirs(os.path.join(ROOT, 'docs/design/themes'), exist_ok=True)
    with open(os.path.join(ROOT, 'docs/design/themes', f'{THEME_ID.get(key, key)}.md'), 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    out = os.path.join(ROOT, '.build/theme-design')
    os.makedirs(out, exist_ok=True)
    for key in THEMES:
        palette_file(key)
        doc(key)
        with open(os.path.join(out, f'colors-{THEME_ID.get(key, key)}.swift.txt'), 'w') as f:
            f.write(colors_block(key))
    print('Generated palettes, docs/design/themes/*.md, and .build/theme-design/colors-*.swift.txt')
